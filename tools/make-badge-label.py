"""Bake the fixed Badges label into native GX alpha runs, at the original tab's 18px ink height."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont, ImageFilter

root = Path(__file__).resolve().parents[1]
font = ImageFont.truetype(str(root / 'assets/fonts/super-mario-256/SuperMario256.ttf'), 240)
box = font.getbbox('Badges')
ink = Image.new('L', (box[2]-box[0], box[3]-box[1]))
ImageDraw.Draw(ink).text((-box[0], -box[1]), 'Badges', font=font, fill=255)
ink = ink.crop(ink.getbbox())
scale = 4
height = 18 * scale
width = round(ink.width * height / ink.height)
ink = ink.resize((width, height), Image.Resampling.LANCZOS)
pad = 6
face = Image.new('L', (width+pad*2, height+pad*2))
face.paste(ink, (pad,pad))
outline = face.filter(ImageFilter.MaxFilter(9))

def runs(mask):
    out = []
    previous = {}
    for y in range(mask.height):
        row = [round(mask.getpixel((x,y))/17)*17 for x in range(mask.width)]
        x=0
        current = {}
        while x < mask.width:
            start=x; alpha=row[x]; x+=1
            while x<mask.width and row[x]==alpha: x+=1
            if alpha:
                key=(start,x-start,alpha)
                if key in previous:
                    index=previous[key]
                    out[index][3]+=1
                else:
                    index=len(out)
                    out.append([start,y,x-start,1,alpha])
                current[key]=index
        previous=current
    return out

header = ['// Generated by tools/make-badge-label.py; font credits: assets/fonts/README.md.',
          '#pragma once', '#include <cstdint>', 'namespace LostPages::BadgeLabelArt {',
          'struct Run { uint16_t x, y, width, height; uint8_t alpha; };',
          f'constexpr float kWidth = {face.width/scale}f, kHeight = {face.height/scale}f;',
          f'constexpr float kPixel = {1/scale}f;']
for name, mask in [('Outline',outline),('Face',face)]:
    values=runs(mask)
    header += [f'constexpr Run k{name}[] = {{']
    header += ['    {'+','.join(map(str,r))+'},' for r in values]
    header += ['};']
    print(name, len(values), 'runs')
header += ['} // namespace LostPages::BadgeLabelArt', '']
(root / 'wiicompiled/runtime/src/lost_pages/lp_badge_label_art.h').write_text('\n'.join(header))

